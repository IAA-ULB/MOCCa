    def D_1D(n):
        """1D Laplacian matrix (nxn) for [1 -2 1] stencil."""
        d = np.zeros((n,n), dtype=np.int8)
        for i in range(n):
            for j in range(n):
                d[i,j] = 0 if (abs(i-j) >= 2) else \
                         1 if (abs(i-j) == 1) else \
                        -2
        return d

