#!/usr/bin/env python3
"""Generate a GNU make dependency table for Fortran .mod files.

Scans the Hephaestos-generated sources of one build tree and emits a make
fragment with, for every module, a rule tying its .mod file to the object
of the file that provides it (empty recipe: the .mod is produced as a side
effect of compiling), and for every object the list of .mod files it
needs. With `-include`, this makes `make -j` safe and recompiles
consumers automatically after interface changes.

Usage:
    python3 scripts/gen_moddeps.py --src-dir DIR --obj-dir DIR --mod-dir DIR
                                   [--out FILE | --dry]

The scan is declaration-based (module names differ from file names in
this code base). Any `use`d name with no provider in the tree (intrinsic
modules like iso_*, mpi_f08, ...) is skipped by absence. Scanning the
generated tree means preprocessor-gated `use` statements already reflect
what this tree compiles; over-listing a module present in the tree is
harmless, under-listing is not.
"""

import argparse
import os
import re
import sys

MODULE_RE = re.compile(
    r"^\s*module\s+(?!procedure\b|function\b|subroutine\b"
    r"|submodule\b|is_duplicate_procedure\b)(?P<name>\w+)",
    re.IGNORECASE,
)
USE_RE = re.compile(
    r"^\s*use\b(?:\s*,\s*(?:non_)?intrinsic\b)?\s*(?:::)?\s*(?P<name>\w+)",
    re.IGNORECASE,
)


def scan_tree(src_dir):
    """Return (providers, users): module -> source file stem, and per-file use lists."""
    providers = {}
    users = {}
    for fname in sorted(os.listdir(src_dir)):
        if not fname.endswith(".f90"):
            continue
        stem = fname[:-4]
        uses = []
        with open(os.path.join(src_dir, fname), encoding="utf-8", errors="replace") as fh:
            for line in fh:
                m = MODULE_RE.match(line)
                if m:
                    providers[m.group("name").lower()] = stem
                    continue
                m = USE_RE.match(line)
                if m:
                    uses.append(m.group("name").lower())
        users[stem] = uses
    return providers, users


def gen_table(src_dir, obj_dir, mod_dir):
    providers, users = scan_tree(src_dir)
    lines = ["# Auto-generated by scripts/gen_moddeps.py - do not edit.", ""]
    for mod, stem in sorted(providers.items()):
        lines.append(f"{mod_dir}/{mod}.mod: {obj_dir}/{stem}.o ;")
    lines.append("")
    for stem, uses in sorted(users.items()):
        mods = sorted({u for u in uses if u in providers})
        if mods:
            deps = " ".join(f"{mod_dir}/{m}.mod" for m in mods)
            lines.append(f"{obj_dir}/{stem}.o: {deps}")
    lines.append("")
    return "\n".join(lines)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--src-dir", required=True,
                   help="directory with the Hephaestos-generated .f90 sources")
    p.add_argument("--obj-dir", required=True,
                   help="object directory for that tree")
    p.add_argument("--mod-dir", required=True,
                   help="module (.mod) directory for that tree")
    p.add_argument("--out", help="output make fragment (default: stdout)")
    p.add_argument("--dry", action="store_true",
                   help="print the table to stdout and exit")
    args = p.parse_args(argv)

    table = gen_table(args.src_dir, args.obj_dir, args.mod_dir)
    if args.dry or not args.out:
        sys.stdout.write(table)
    else:
        os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
        with open(args.out, "w", encoding="utf-8") as fh:
            fh.write(table)


if __name__ == "__main__":
    main()
