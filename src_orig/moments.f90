  subroutine TurnOffConstraints(iter)
    !---------------------------------------------------------------------------
    ! Checks all of the constraints for temporary ones and 
    ! sees if they have reached their expiration iteration number.
    !---------------------------------------------------------------------------
    integer, intent(in)   :: iter
    type(Moment), pointer :: Current

    1 format ('Turning of constraint on multipole moment.')
    2 format (' ' , a2 , ' l = ', i2, ' m = ', i2)
    3 format ('after ', i4, ' iterations.') 
    4 format ('------------------------------------------')

    Current => root

    do while(associated(Current%next))
            Current => Current%next
            if(Current%ConstraintType .eq. 0) cycle
    if(Current%iteration      .le. 0) cycle
            if(iter                   .gt. Current%iteration) then
                    Current%Constrainttype=0
                    print 4
                    print 1
                    if(Current%Impart) then
                            print 2, 'Im', current%l, current%m
                    else
                            print 2, 'Re', current%l, current%m
                            print 3, iter
                    endif
                    print 4
            endif
    enddo
  end subroutine TurnOffConstraints

  function checkconstraints() result(projectpresent)
    !---------------------------------------------------------------------------
    ! Check all moments for constrainttype == 2.
    !---------------------------------------------------------------------------
    
    logical :: projectpresent
    type(Moment), pointer :: current

    projectpresent = .false.
    Current => Root
    do while(associated(Current%next))
        Current => Current%Next
        if(Current%constrainttype .eq. 2) then
            projectpresent = .true.
            return
        endif
    enddo

  end function checkconstraints

  recursive function FindMoment(l,m,Impart,StartMoment) result(FoundMoment)
    !---------------------------------------------------------------------------
    ! Subroutine that finds a pointer to the moment, specified by multipole
    ! values l,m and whether it is a real or imaginary part.
    ! For maximum efficiency, it is possible to specify a StartMoment, so that
    ! the search starts at that specific moment.
    ! Ex: Tantalus can find Im(Q_{22}) faster if it starts from Re(Q_{20}).
    !
    ! The result is null if the moment isn't found.
    !---------------------------------------------------------------------------
    integer, intent(in)                        :: l,m
    logical, intent(in)                        :: Impart
    type(Moment), intent(in), pointer, optional:: StartMoment
    type(Moment), pointer                      :: Current, FoundMoment

    nullify(Current); nullify(FoundMoment)

    if(present(StartMoment)) then
      Current => StartMoment
    else
      Current => Root
    endif

    if((Current%l.eq.l) .and. (Current%m .eq. m) .and.                       &
      &               (Impart.eqv.Current%Impart)) then
        !Then we've found the correct moment.
        FoundMoment => Current
        return
    endif

    do while(associated(Current%Next))
      Current => Current%Next
      if((Current%l.eq.l) .and. (Current%m .eq. m) .and.                       &
      &               (Impart.eqv.Current%Impart)) then
        !Then we've found the correct moment.
        FoundMoment => Current
        return
      endif
    enddo
    if(present(StartMoment)) then
      ! If this part of the code gets reached, we picked a bad starting point.
      ! So we start over again!
      FoundMoment => FindMoment(l,m,Impart)
    else
      FoundMoment => null()
    endif
    return
  end function FindMoment

