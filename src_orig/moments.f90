  subroutine PrintMoment_electric(ToPrint)
    !---------------------------------------------------------------------------
    ! This subroutine provides the printing of all relevant info of a Moment.
    !---------------------------------------------------------------------------
    ! Special printing rules are provided for
    ! - l = 0 moment => Particle numbers
    ! - l =-2 moment => RMS radii
    ! - l = 4 moment => r^4 radii
    !---------------------------------------------------------------------------
     
    class(Moment),       intent(in) :: ToPrint
    character(len=2)                :: ReIm
    real(KIND=dp)                   :: printedValue(4)

      1 format (A2, '  Q_{', 2i2, '}', 4(1x, f15.4) )
     11 format (A2, '  Q_{', 2i2, '}', 4(1x,es15.4) )      
      2 format ('Constrained ',  49x, f15.4)
     21 format ('Constrained ',   1x, f15.4)
     22 format ('Constrained ',  17x, f15.4)
      3 format (' Particles  ',  4(1x,f15.4))
      4 format (' RMS radius ',  4(1x,f15.4))
     41 format (' Fourth mom.',  4(1x,f15.4)) 
      5 format (A2, ' La_{',i2,i2,'}',   49x,  f15.4)
     51 format (A2, ' La_{',i2,i2,'}',    1x,  f15.4)
     52 format (A2, ' La_{',i2,i2,'}',   17x,  f15.4)
      6 format (A2, ' De_{',i2,i2,'}',   49x,  e15.7) 
     61 format (A2, ' De_{',i2,i2,'}',    1x,  e15.7) 
     62 format (A2, ' De_{',i2,i2,'}',   17x,  e15.7) 

    select case(ToPrint%l)
    !---------------------------------------------------------------------------
    case(0)
      ! Printing the total number of particles
      print 3, sqrt(4*pi)*ToPrint%Value,  sqrt(4*pi)*ToPrint%ChargeValue,      &
      &        sqrt(4*pi)*sum(ToPrint%Value)
    !---------------------------------------------------------------------------
    case(-2)
      ! Printing RMS charge radii
      ! Avoid division by 0 in case of one nucleon number being zero
      printedValue(:) = 0.0_dp
      if ( neutrons .gt. 0.0_dp ) then
        printedValue(1) = sqrt(ToPrint%Value(1)/Neutrons)
      endif
      if ( protons  .gt. 0.0_dp ) then
        printedValue(2) = sqrt(ToPrint%Value(2)/Protons)
        printedValue(3) = sqrt(ToPrint%ChargeValue/Protons)
      endif
      printedValue(4) = sqrt(sum(ToPrint%Value)/(Neutrons+Protons))
      print 4, printedValue(1:4)

    case(-4)
      ! Printing <r^4>^{1/4}
      printedValue(:) = 0.0_dp
      if ( neutrons .gt. 0.0_dp ) then
        printedValue(1) = (ToPrint%Value(1)/Neutrons)**(1.0d0/4.0d0)
      endif
      if ( protons  .gt. 0.0_dp ) then
        printedValue(2) = (ToPrint%Value(2)/Protons)**(1.0d0/4.0d0)
        printedValue(3) = (ToPrint%ChargeValue/Protons)**(1.0d0/4.0d0)
      endif
      printedValue(4) = (sum(ToPrint%Value)/(Protons+Neutrons))**(1.0d0/4.0d0)
      print 41, printedValue(1:4)

    !---------------------------------------------------------------------------
    case DEFAULT
      !All other "normal" multipole moments
      ReIm = 'Re'
      if(ToPrint%Impart) ReIm = 'Im'

      if (ToPrint%l .lt. 6) then
       ! Ordinary print
       print 1, ReIm, ToPrint%l, ToPrint%m, ToPrint%Value(1), ToPrint%Value(2),&
       &        ToPrint%Chargevalue,  Sum(ToPrint%Value)
      else
       ! Start using scientific notation
       print 11,ReIm, ToPrint%l, ToPrint%m, ToPrint%Value(1), ToPrint%Value(2),&
       &        ToPrint%Chargevalue,  Sum(ToPrint%Value)
      endif
  
      if(ToPrint%ConstraintType.ne.0) then
        select case(ToPrint%isoswitch)
        case(0)
          print 2,  ToPrint%Constraint
          print 6, ReIm, ToPrint%l, Toprint%m, ToPrint%Deviation
          print 5, ReIm, ToPrint%l, Toprint%m, ToPrint%Multiplier
        case(1)
          print 21,  ToPrint%Constraint
          print 61, ReIm, ToPrint%l, Toprint%m, ToPrint%Deviation
          print 51, ReIm, ToPrint%l, Toprint%m, ToPrint%Multiplier        
        case(2)
          print 22,  ToPrint%Constraint
          print 62, ReIm, ToPrint%l, Toprint%m, ToPrint%Deviation
          print 52, ReIm, ToPrint%l, Toprint%m, ToPrint%Multiplier
        end select
      endif
    end select
    !---------------------------------------------------------------------------
  end subroutine PrintMoment_electric

  subroutine PrintMoment_divJ(ToPrint)
