  function CalculateTotalQl(l) result(ql)
    !---------------------------------------------------------------------------
    ! Calculates the current value of Q_{l} for a given value of l.
    ! Q_l = \sqrt{\Sum_{m = -l,..,l} [ < Re Q_{lm} >**2 + < Im Q_{lm}**2 > ] }
    !     = \sqrt{\Sum_{m = 0,..,l} f(m)[ < Re Q_{lm} >**2 + < Im Q_{lm}**2 >]}
    !
    !  where f(0) = 1 and f(m\not=0) = 2.
    !---------------------------------------------------------------------------

    integer, intent(in)   :: l
    type(Moment), pointer :: Current
    real(KIND=dp)         :: ql(3), fm
    integer               :: m
    
    ql = 0.0_dp ; m=0
    Current => FindMoment(l,0,.false.)
    do while(m.lt.l .and. .not.associated(Current))
        m = m+1
        Current => FindMoment(l,m,.false.)
        if(.not.associated(Current)) then
           Current => FindMoment(l,m,.true.)
        endif
    enddo
    if(.not.associated(Current)) then
         return
    endif

    ql(1:2) =     Current%Value**2
    ql(3)   = sum(Current%Value)**2
    do while(associated(Current%Next))
      Current  => Current%Next
      if(Current%l .ne.l) exit

      if(Current%m.ne.0) then
        fm=2
      else
        fm=1
      endif

      ql(1:2) = ql(1:2) + Current%Value**2*fm
      ql(3)   = ql(3)   + sum(Current%Value)**2*fm
    enddo
    nullify(Current)
    ql = sqrt(ql)
  end function CalculateTotalQl

