  subroutine CalculateMoments()
    !---------------------------------------------------------------------------
    ! Subroutine that
    !   1) Calculates the values of all multipole (mass and magnetic) moments
    !   2) Calculate the quadrupole moments in different representations
    !---------------------------------------------------------------------------
    use Densities
    
    type(Moment), pointer :: Current

    call start_timer(T_moments)

    !---------------------------------------------------------------------------
    ! First, we need to calculate the cutoff function
    call CompCutoff

    !---------------------------------------------------------------------------
    ! Calculate the electric multipole moments
    nullify(Current) ;  Current => Root
    call Current%Calculate(Current) !  electric monopole
    !---------------------------------------------------------------------------
    do while(associated(Current%Next))
        Current => Current%Next
        call Current%Calculate(Current)
    enddo
    !---------------------------------------------------------------------------
    ! Calculate the magnetic multipole moments 
$NTR    nullify(Current) ;  Current => Root_mag
$NTR    do while(associated(Current%Next))
$NTR        Current => Current%Next
$NTR        call Current%Calculate(Current)
$NTR    enddo

    !---------------------------------------------------------------------------
    ! Calculate the multipole moments of divJ
    nullify(Current) ;  Current => Root_divJ
    call Current%Calculate(Current)           !norm of div J
    do while(associated(Current%Next))
       Current => Current%Next
       call Current%Calculate(Current)
    enddo
    
    call CalcQuadrupoleAlt()

    call stop_timer(T_moments)

    return
  end subroutine CalculateMoments
  
  subroutine Calculate_electric(ToCalculate)
    !---------------------------------------------------------------------------
    ! This subroutine calculates the value of a mass/electric multipole moment.
    !
    ! Input:
    !        Tocalculate :  mass/electric multipole moment to be calculated
    !---------------------------------------------------------------------------
    use Densities, only : D_I_I, chargedensity
   
    class(Moment),        intent(inout) :: ToCalculate
    integer                             :: it

    ! Save the history
    Tocalculate%history = tocalculate%value

    !Initialise
    ToCalculate%Value      = 0.0_dp
    ToCalculate%Squared    = 0.0_dp

    !---------------------------------------------------------------------------
    ! Calculate the new value for ordinary constraints
    do it=1,2
      ToCalculate%Value(it)      = sum(ToCalculate%SpherHarm*D_I_I(:,it))   * dv
      ToCalculate%Squared(it)    = sum(ToCalculate%SpherHarm**2*D_I_I(:,it))* dv
    enddo
    ToCalculate%ChargeValue      =  &
    &             dv*sum(ToCalculate%SpherHarm*   chargedensity(1:nx*ny*nz,1,1))

    ! Check for problems
    if(any(ToCalculate%Value.eq.ToCalculate%Value+1)) then
      call stp('NaN inside a multipole moment.')
    endif

    ! Set the deviation
    if(ToCalculate%ConstraintType.ne.0) then
      select case(ToCalculate%isoswitch)
      case(0)
        ToCalculate%deviation    =                                             &
        &                 abs(sum(ToCalculate%Value)   - ToCalculate%constraint)
      case(1,2)
        it = Tocalculate%isoswitch
        ToCalculate%deviation    =                                             &
        &                 abs(    ToCalculate%Value(it)- ToCalculate%constraint)
      end select
    endif
    call CalcBeta(ToCalculate)

    return
  end subroutine Calculate_electric
  
  subroutine Calculate_magnetic(ToCalculate)
    !---------------------------------------------------------------------------
    ! This subroutine calculates the magnetic multipole moment by integrating 
    ! the spin and current density over the mesh with the appropriate 
    ! spherical harmonic. 
    ! 
    ! There are two integrations to be performed here
    !
    ! < Q^m_(lm,s) > =   -  1/2 int d^3r  (nabla_mu s_mu)       Q_lm
    ! < Q^m_(lm,l) > =   -      int d^3r  (nabla_mu (r x j)_mu) Q_lm
    !                =   +      int d^3r r_mu (nabla x j)_mu    Q_lm
    !
    ! Note the 'surprise!' factor of two, since our Pauli matrices have
    ! eigenvalues +/-1 instead of +/- 0.5. 
    ! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
    ! Input:
    !        Tocalculate :  mass/electric multipole moment to be calculated
    !---------------------------------------------------------------------------
$NTR    use densities, only : der_C_I_N, der_D_I_S

    class(Moment),        intent(inout) :: ToCalculate
$NTR    integer                             :: it,mu
$NTR    real(KIND=dp)                       :: rj(nx*ny*nz,3)

    !Initialise
    ToCalculate%VectorValue     = 0.0_dp
    ToCalculate%PhysVectorValue = 0.0_dp
    
    !---------------------------------------------------------------------------
    ! Orbital function to integrate over
    ! - div.(r x j) 
    !   = - sum_ijk epsilon_ijk nabla_i (r_j j_k)
    !   = - sum_ijk epsilon_ijk [ (nabla_i r_j) j_k + r_j (nabla_i j_k) ]
    !   = - sum_ijk epsilon_ijk r_j (nabla_i j_k)
    !   =   r.(nabla x j)
    ! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
$NTR    do it=1,2
$NTR      !                                [nabla x j]_x = nabla_y j_z - nabla_z j_y
$NTR      rj(:,1) = meshgrid_shifted(:,1) * &
$NTR      &                              (der_C_I_N(:,2,3,it) - der_C_I_N(:,3,2,it))
$NTR      !                                [nabla x j]_y = nabla_z j_x - nabla_x j_z
$NTR      rj(:,2) = meshgrid_shifted(:,2) * &
$NTR      &                              (der_C_I_N(:,3,1,it) - der_C_I_N(:,1,3,it)) 
$NTR      !                                [nabla x j]_z = nabla_x j_y - nabla_y j_x
$NTR      rj(:,3) = meshgrid_shifted(:,3) * &
$NTR      &                              (der_C_I_N(:,1,2,it) - der_C_I_N(:,2,1,it)) 
$NTR  
$NTR      ! spin part = -1/2 Y_lm div.s(r)
$NTR      do mu=1,3
$NTR        ToCalculate%VectorValue(mu,1,it)    = - 0.5_dp*                        &
$NTR        &                    sum(ToCalculate%SpherHarm(:)*Der_D_I_S(:,mu,mu,it))
$NTR      enddo
$NTR      ! Orbital part -2/(l+1) Y_lm div(r x j) = 2/(l+1) Y_lm r.(rot j)
$NTR      do mu=1,3
$NTR        ToCalculate%VectorValue(mu,2,it) =  2.0_dp/(ToCalculate%l+1) *         &
$NTR        &                                 sum(ToCalculate%SpherHarm(:)*rj(:,mu))
$NTR      enddo  
$NTR    enddo
$NTR    !---------------------------------------------------------------------------
$NTR    ! Calculate the contribution to the physical magnetic multipole moment
$NTR    do it=1,2
$NTR        do mu=1,3
$NTR            toCalculate%Physvectorvalue(mu,it) =                &
$NTR            &    g_spin (it) * tocalculate%vectorvalue(mu,1,it) &
$NTR            &  + g_orbit(it) * tocalculate%vectorvalue(mu,2,it)
$NTR        enddo
$NTR    enddo
$NTR    ToCalculate%vectorValue       = ToCalculate%vectorValue*dv
$NTR    ToCalculate%physvectorValue   = ToCalculate%physvectorValue*dv

    return
  end subroutine Calculate_magnetic

  subroutine Calculate_multipole_divJ(ToCalculate)
    !---------------------------------------------------------------------------
    ! This subroutine calculates the value of a multipole moment of the 
    !  vector component of the spin-current density J_mn = C^{1,nabla sigma}_mn
    !
    ! Input:
    !        Tocalculate :  multipole moment to be calculated
    !---------------------------------------------------------------------------
    use Densities, only : divJ
    use derivatives
  
    class(Moment),        intent(inout) :: ToCalculate
    integer                             :: it

    ! Save the history
    Tocalculate%history = tocalculate%value

    !Initialise
    ToCalculate%Value      = 0.0_dp
    ToCalculate%Squared    = 0.0_dp  !Unused, but zeroed anyway

    !---------------------------------------------------------------------------
    ! Calculate these values    
    do it=1,2
      ToCalculate%Value(it)      = sum(ToCalculate%SpherHarm*divJ(:,it))    *dv
    enddo
    ! Not sure what a "charge density" J_mn would be, set to zero for now
    ToCalculate%ChargeValue      =  0.0d0
    
    return
  end subroutine Calculate_multipole_divJ

  subroutine CalcBeta(Mom)
  !-----------------------------------------------------------------------------
  ! Function that calculates the beta_lm deformation parameters associated with
  ! an (electric) multipole moment Q_lm.
  !-----------------------------------------------------------------------------
    type(Moment), intent(inout) :: Mom
    real(KIND=dp)               :: R, factor

    R = 1.2_dp  * (neutrons + protons)**(1.0_dp/3.0_dp)
    factor = 4.0_dp * pi /(3.0_dp * R**(Mom%l))

    Mom%Beta(:) = 0.0_dp
    if ( neutrons .gt. 0.0_dp ) Mom%Beta(1) = factor*Mom%Value(1)/neutrons
    if ( protons  .gt. 0.0_dp ) Mom%Beta(2) = factor*Mom%Value(2)/protons
    if ( protons  .gt. 0.0_dp ) Mom%Beta(3) = factor*Mom%ChargeValue/protons

    Mom%Beta(4) = factor*sum(Mom%Value)/(neutrons+protons)
  end subroutine CalcBeta
  
  subroutine CalcQuadrupoleAlt()
    !---------------------------------------------------------------------------
    ! Calculates the Quadrupole moments in their various representations.
    ! See the formulas in 
    !
    !   W. Ryssens, Symmetry breaking in nuclear mean-field models, 
    !     PhD Thesis, ULB (2016)
    !---------------------------------------------------------------------------
    ! The off-diagonal components of the quadrupole tensor are kept, but not
    ! used at the moment....
    !---------------------------------------------------------------------------
    type(Moment),pointer :: Q20, RQ22 , IQ22, RQ21, IQ21
    integer              :: i

    ! Finding the moments. Note that moments that are not allowed will not be
    ! found and the pointers will be null.
    Q20 =>FindMoment(2,0,.false.     )
    RQ21=>FindMoment(2,1,.false., Q20)
    IQ21=>FindMoment(2,1,.true. , Q20)
    RQ22=>FindMoment(2,2,.false., Q20)
    IQ22=>FindMoment(2,2,.true. , Q20)

    QCartesian = 0.0_dp

    !Cartesian Moments
    do i=1,2
      ! a) Diagonal elements
      QCartesian(1,1,i) = - (sqrt(5.0_dp/( 4.0_dp * pi)))**(-1)  * &
      &         ( Q20%Value(i) - sqrt(6.0_dp) * RQ22%Value(i) )
      QCartesian(2,2,i) = - (sqrt(5.0_dp/( 4.0_dp * pi)))**(-1)  * &
      &         ( Q20%Value(i) + sqrt(6.0_dp) * RQ22%Value(i) )
      QCartesian(3,3,i) =   (sqrt(5.0_dp/(16.0_dp * pi)))**(-1)  * &
      &           Q20%Value(i)

      ! b) Off-diagonal elements
      if(associated(RQ21)) then
        ! RQ21 = sqrt(15/(pi 4)) zx
        QCartesian(1,3,i) = RQ21%Value(i) * sqrt(4.0_dp * pi/ (15.0_dp))
        QCartesian(3,1,i) = QCartesian(1,3,i)
      endif
      if(associated(IQ21)) then
        !IQ21 = sqrt(15/(4 pi)) yz
        QCartesian(2,3,i) = IQ21%Value(i) * sqrt(4.0_dp * pi/ (15.0_dp))
        QCartesian(3,2,i) = QCartesian(2,3,i)
      endif
      if(associated(IQ22)) then
        !IQ22 = sqrt(15/(4*pi)) xy
        QCartesian(1,2,i) = IQ22%Value(i) * sqrt(4.0_dp * pi/ (15.0_dp))
        QCartesian(2,1,i) = QCartesian(1,2,i)
      endif
    enddo

    !Total moments
    QCartesian(:,:,3)=sum(QCartesian(:,:,1:2),3)

    !---------------------------------------------------------------------------
    ! Q & Gamma representation
    do i=1,3
      Q(i) = sqrt(2.0_dp/3.0_dp *                                              &
      &   ( QCartesian(1,1,i)**2 + QCartesian(2,2,i)**2 + QCartesian(3,3,i)**2))
      if(abs(QCartesian(3,3,i)).gt.1d-08 ) then
        G(i) = atan2((QCartesian(1,1,i) - QCartesian(2,2,i)),                  &
        &                                     (sqrt(3.0_dp)* QCartesian(3,3,i)))
      else
        G(i) = 0.0_dp
      endif
    enddo
    ! iq1 & iq2
    do i=1,3
      iq1(i) = Q(i) * cos(G(i)) - 1/sqrt(3.0_dp) * Q(i) * sin(G(i))
      iq2(i) = 2/sqrt(3.0_dp)*Q(i)*sin(G(i))
    enddo
  end subroutine CalcQuadrupoleAlt
  
  pure function LegacyQuad (iq1,iq2) result(Constraints)
    !---------------------------------------------------------------------------
    ! Function that converts the legacy iq1, iq2 input from EV8 to new style
    ! input on Q20 & Q22.
    ! See conversion coefficients in W.Ryssens et al., CPC (to be published)
    !---------------------------------------------------------------------------
    real(KIND=dp), intent(in) :: iq1,iq2
    real(KIND=dp)             :: Constraints(2)
    real(KIND=dp)             :: Q20, Q22
    Constraints=0.0_dp

    ! Q20 = 1/2 *sqrt(5/(16*pi))* ( 2 * q1 + q2)
    Q20 = 0.5_dp *sqrt(5.0_dp/(16.0_dp * pi)) * ( 2 * iq1 + iq2 )

    ! Q22 = 3/2*q2 * sqrt(5/(4*pi)) * 1/(2 * sqrt(6))
    Q22 = 1.5_dp * iq2 * sqrt(5.0_dp/(4.0_dp * pi)) /(2 * sqrt(6.0_dp))

    Constraints(1) = Q20
    Constraints(2) = Q22

  end function LegacyQuad
  
