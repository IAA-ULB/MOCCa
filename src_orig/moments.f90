!===============================================================================
! 
! Module treating the calculation of, printing of and constraints on the 
! multipole moments of the various mean-field densities. 
!
! Spherical harmonics are taken to be in the convention of Messiah.
! They are, in terms of spherical coordinates:
!
!        Y_{l}^{m} = (-1)^{m}[(2*l+1)/4\pi (l-m)!/(l+m)!]^{1/2}
!                 *    P^{m}_{l}(cos(\theta)) e^{i m \phi}
!
! where the P^{m}_{l} are the associated Legendre Polynomials and -l <= m <= l.
! These expression on the mesh are automatically generated by recursion formula.
!
! The code "talks" about the real and imaginary parts of these moments.
! The only values for m that appear in the code are positive.
!
!   Re Y_lm =  1/2 * (Y_l+m + Y_l-m)
!   Im Y_lm = -i/2 * (Y_l+m - Y_l-m)
!
! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - 
! 
! The electric multipole moments are
!      \langle \hat{Q}^e_{lm} \rangle = \int d^3r rho(r) r^l Y_{lm} 
! The magnetic multipole moments are
!      \langle \hat{Q}^m_{lm} \rangle = Q^m_lm,spin + Q^m_lm,orbit 
!      Q^m_lm,spin                = 0.5*\int d^3r s_m(r) nabla_m(r^l Y_{lm}) 
!      Q^m_lm,orbit               =     \int d^3r (rxj)_m(r) nabla_m(r^l Y_{lm}) 
!
! Note that the magnetic moments are not calculated in this way by the code, 
! but rather by partial integration and using a vector identity for the orbit
! part.
!
! The magnetic multipole moments do not appear yet in this code, as they are
! time-odd.
!
! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
! The rms radius is treated on the same footing as the multipole moments here
! even though there is no spherical harmonic corresponding to it. It is put into
! the linked list for l=-1. 
!
! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
! For the electric multipole moments, practical quantities to investigate are
!
! Dimensionless deformation Betas
!  Beta_lm  = 4 * pi /( 3 * R_0**l * A) < Q^e_{lm} >
!           where R0 = 1.2A**(1/3)
!
! Total deformation
!  Q_l = \sqrt{ \Sum_{m = 0,..,l} f(m) [ < Re Q_{lm} >**2 + < Im Q_{lm}**2 > ]}
!         with f(m) = 2 if m \not = 0 and f(m) = 1 for m = 0.
!
! For more conversion formulae see:
!
!   W.Ryssens, V. Hellemans, M. Bender & P.-H. Heenen, CPC 187 (2015) 175-194
!   W.Ryssens, PhD Thesis (2016)
!
! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - 
!
!  For constraints, two options exist for every moment independently
!  - Augmented Lagrangian with fixed intensity
!  - Constraints with projection on feasible set
!
!  This is encoded for every multipole moment separately 
!   (0) No constraint
!   (1) Augmented Lagrangian
!   (2) Projection on feasible set
!
!  For the moment only the total value of the electric multipole moments can be
!  constrained. 
!
!-------------------------------------------------------------------------------
!
! There is a redundancy in the choice of parameterization of the multipole 
! moments: it depends on the choices made for the Cartesian reference frame. 

! There are six possibilities, corresponding to the permutations of the 
! axes of the intrinsic frame. 
!
! (x,y,z), (x,z,y), (y,x,z), (y,z,x), (z,x,y), (z,y,x)
!
! which all correspond to different parameterizations of the spherical
! coordinates in terms of (x,y,z).
!
! The distinction is made by two parameters:
!     QuantisationAxis = X/Y/Z (1,2,3)
! which determines which of the Cartesian coordinates determines the 
! azimuthaml angle theta
!     x_i = r cos(theta).
! The second parameter
!     SecondaryAxis = 1/2
! simply determines the reference for the angle \phi. It determines the order of
! the two other (non-quantization) axes. 1 corresponds to lexographical order
! (x,y) while 2 corresponds to non-lexicographical order (y,x).
!
! The angle phi is determined by
!     \phi = atan2(x_2, x_1)
!
! Examples:
!    (QuantisationAxis, SecondaryAxis,Permutation)
!    (3,1, (x,y,z))
!    (3,2, (y,x,z))
!    (2,1, (x,z,y))
!    (2,2, (z,x,y))
!    (1,1, (y,z,x))
!    (1,2, (z,y,x))
!
! Note that changing from the ordinary (x,y,z) has profound consequences
! regarding which non-physical multipole moments. 
!-------------------------------------------------------------------------------
!===============================================================================
  use geninfo
  use sphericalharmonics

  implicit none
  
  !-----------------------------------------------------------------------------
  ! The technical feat of treating multipole moments on an equal footing for 
  ! any kind of (l,m) or nature of the multipole moment is accomplished by 
  ! using several linked lists of these moment type objects.
  !-----------------------------------------------------------------------------
  type Moment
      !-------------------------------------------------------------------------
      !Principal and magnetic quantum number of the multipole moment
      integer :: l,m
      !Looking at the real(.false.) or imaginary(.true.) part
      logical :: ImPart
      ! Nature of the multipole moment. 
      ! Accepted values:
      ! a) electric
      integer :: momtype
      !-------------------------------------------------------------------------
      !The SpherHarm variable contains the values of the associated Qlm.
      !-------------------------------------------------------------------------
      real(KIND=dp), allocatable  :: SpherHarm(:)
      !-------------------------------------------------------------------------
      ! Integer controlling the type of constraint on the multipole moment.
      ! 0 - unconstrained
      ! 1 - Augmented Lagrangian
      ! 2 - Projection on feasible set
      !-------------------------------------------------------------------------
      integer       :: ConstraintType
      !-------------------------------------------------------------------------
      ! Number of iterations to employ the constraint for. Useful for putting 
      ! temporary constraint in order to initialize a calculation.
      integer       :: Iteration=-1
      !-------------------------------------------------------------------------
      ! Calculated value of the moment with and without cutoff,
      ! for neutrons and protons.
      !-------------------------------------------------------------------------
      real(KIND=dp) :: Value(2)
      !-------------------------------------------------------------------------
      ! Value of the multipole at the previous iteration
      real(KIND=dp) :: history(2)
      !-------------------------------------------------------------------------
      ! Calculated value of the moment SQUARED.
      ! So < Q_{lm}^2 > and < Q_{lm}>^3
      !-------------------------------------------------------------------------
      real(KIND=dp) :: Squared(2)
      !-------------------------------------------------------------------------
      ! Value of the constraint on the multipole moment.
      real(KIND=dp) :: Constraint
      !-------------------------------------------------------------------------
      ! Value of the current value of the Lagrange multiplier
      real(KIND=dp) :: multiplier
      !-------------------------------------------------------------------------
      ! Deviation of the constraint with respect to the asked for value.
      real(KIND=dp) :: deviation
      !-------------------------------------------------------------------------
      ! Intensity of the constraint
      real(KIND=dp) :: Intensity
      !-------------------------------------------------------------------------
      ! Pointers to the previous and next item in the linked list.
      !-------------------------------------------------------------------------
      type(Moment), pointer  :: Prev
      type(Moment), pointer  :: Next
      !-------------------------------------------------------------------------
      ! Deformation parameter Beta_lm associated with the moment.
      ! (neutrons,protons,total)
      !-------------------------------------------------------------------------
      real(KIND=dp) :: Beta(3)
      !-------------------------------------------------------------------------
      ! Logical: if True, use the Lagrange multiplier as read from file.
      logical :: multfromfile = .false.
      logical :: continue     = .false.
      !-------------------------------------------------------------------------
      ! Procedure pointer to the routine used to calculate the moment.
      procedure(Calculate_electric),   pointer, nopass :: Calculate
      !-------------------------------------------------------------------------
      ! Procedure pointer to the routine used to print output of the moment.
      procedure(PrintMoment_electric), pointer, nopass :: PrintMoment
      !-------------------------------------------------------------------------
  end type Moment

  !-----------------------------------------------------------------------------
  !Maximum degree of the multipole components that are considered. Default = 10
  integer      :: MaxMoment=10, maxmoment_J0=2
  !-----------------------------------------------------------------------------
  ! Starting point for the linked list of moments.
  !-----------------------------------------------------------------------------
  type(Moment),save, pointer :: Root         ! Electric multipole moments
  !-----------------------------------------------------------------------------
  ! CutoffType
  ! 0 : Density-dependent cutoff
  ! 1 : Spherical cut-off
  !-----------------------------------------------------------------------------
  integer       :: CutoffType=0
  !-----------------------------------------------------------------------------
  !Parameters of the cutoff function.
  ! 1 + exp[(\DeltaR - radd)/acut]
  ! Default values are the ones from K. Rutz et al, Nucl. Phys. A590 (1995) 690
  !-----------------------------------------------------------------------------
  real(KIND=dp) :: radd = 4._dp,acut=0.4_dp
  !-----------------------------------------------------------------------------
  !Cutoff function
  ! For 1) Neutrons, 2) Protons
  real(KIND=dp), allocatable, target :: Cutoff(:,:)
  !-----------------------------------------------------------------------------
  ! Slowdown of the readjustment of the Lagrange multipliers
  !-----------------------------------------------------------------------------
  real(KIND=dp)  :: ReadjustSlowDown=0.1_dp
  !-----------------------------------------------------------------------------
  !Pointer to the cutoff procedure chosen.
  !-----------------------------------------------------------------------------
  abstract interface
        subroutine comp_cutoff()
        end Subroutine
  end interface
  procedure(comp_cutoff), pointer :: CompCutoff
  !-----------------------------------------------------------------------------
  ! Quadrupole moments in different representations, for printing purposes only.
  !
  ! Cartesian: QCartesian
  ! (Q,gamma): Q, G
  ! iq1, iq2 : iq1, iq2
  !-----------------------------------------------------------------------------
  real(kind=DP)   :: QCartesian(3,3,3), Q(3), G(3), iq1(3), iq2(3)
  !-----------------------------------------------------------------------------
  ! Quantisation axis of the moments.
  integer :: QuantisationAxis=3, SecondaryAxis=1
  !-----------------------------------------------------------------------------
  ! Contribution to the single-particle Hamiltonian by the constraints
  !  a) Electric multipole => Constraint_I_I => F_I_I
  !-----------------------------------------------------------------------------
  real(kind=dp), allocatable, target :: Constraint_I_I(:,:)
  !-----------------------------------------------------------------------------
  ! If true, the code takes ALL of the information on the constrained moments
  ! from the read-in wavefunction file.
  logical :: ContinueAll = .false.

contains
  
  subroutine IniMoments()
    !---------------------------------------------------------------------------
    ! This routine sets up all of the linked lists needed.
    ! 
    ! 1) The first moment ( l=0, m=0 ) is created. It is called 'Root'.
    !    
    ! 2) The values of all the desired spherical harmonics
    !    (l=0,..., MaxMoment, m=0,...,MaxMoment) are computed.
    !
    ! 3) The routine creates all the necessary moments using subroutine
    !    NewMoment and links them in the following order:
    !    (l,m, R/I): (0,0), (1,0), (1,1,R), (1,1,I), (2,0), (2,1,R), (2,1,I),...
    !    Moments that are automatically zero (by symmetry) are not created by
    !    NewMoment and are absent from the list.
    ! 
    ! 4) Tantalus here detects the nonphysical moments. Not yet applicable to 
    !    this version.
    !
    ! 5) After all this, a final addition to the linked list is made: the
    !    radius squared. (This can be used to calculate the rms radius
    !    obviously).
    !
    ! --------------------------------------------------------------------------
    integer :: l,m,ImPart,i,j,k
    ! Meshes containing the values of all associated Legendre Polynomials
    ! Some dimensions start at index 0, because l and m can both be 0
    real(KIND=dp),allocatable  :: SpherHarmMesh(:,:,:,:,:,:)
    type(Moment),pointer       :: NextMoment,Current
    
    real(KIND=dp), pointer     :: harm_3D(:,:,:)
    
    allocate(SpherHarmMesh(nx,ny,nz,0:MaxMoment,0:MaxMoment,2))
    
    !---------------------------------------------------------------------------
    ! Create the first Multipole moment: l=0, m=0
    nullify(Root) ;    allocate(Root)
    Root%l=0      ;    Root%m=0
    allocate(Root%SpherHarm(nx*ny*nz))
    
    !---------------------------------------------------------------------------
    !This is the l=0,m=0 spherical harmonic
    Root%SpherHarm=1.0_dp/sqrt(4.0_dp*pi) 
    Root%Impart=.false.
    Root%ConstraintType=0
    Root%Calculate   => Calculate_electric
    Root%PrintMoment => PrintMoment_electric
    nullify(Root%Prev) ;  nullify(Root%Next)
    
    !---------------------------------------------------------------------------
    ! Calculating all the spherical harmonics
    call GenSphericalHarmonics(maxmoment,nx,ny,nz,meshx,meshy,meshz,           & 
    &                          SpherHarmMesh,quantisationaxis,secondaryaxis)
    
    !---------------------------------------------------------------------------
    ! Starting the initialization
    nullify(Current)      ;  allocate(Current)     ; Current=>Root
    nullify(Current%Next) ;  nullify(Current%Prev) ; nullify(NextMoment)
    
    !---------------------------------------------------------------------------
    !Creating all the moments and assigning each moment the spherical harmonic
    ! a) The electric moments
    do l=1, MaxMoment
      do m=0,l
        do ImPart=0,1
          NextMoment => NewMoment_electric(l,m,ImPart)
          !Placing the moment in the list
          if(associated(NextMoment)) then
            harm_3D(1:nx,1:ny,1:nz) => NextMoment%SpherHarm(:)
            harm_3D=SpherHarmMesh(:,:,:,l,m,Impart+1)
            ! Putting the pointers in the correct direction
            NextMoment%Prev => Current
            Current%Next    => NextMoment
            Current         => NextMoment
            nullify(NextMoment)
          endif
        enddo
      enddo
    enddo
    !---------------------------------------------------------------------------
    !Appending the radius squared to the ordinary list
    NextMoment   => NewMoment_electric(-2,0,0)
    harm_3D(1:nx,1:ny,1:nz) => NextMoment%SpherHarm(:)
    NextMoment%Calculate    => Calculate_rms  

    do k=1,nz
      do j=1,ny
        do i=1,nx
          harm_3D(i,j,k) = meshx(i)**2 + meshy(j)**2 + meshz(k)**2
        enddo
      enddo
    enddo
    
    Current%Next    => NextMoment
    NextMoment%Prev => Current
    !---------------------------------------------------------------------------
    return
  end subroutine IniMoments

  function NewMoment_Electric(l,m,ImPart) result(newmoment)
    !---------------------------------------------------------------------------
    ! This subroutine creates a new electric multipole moment, provided the 
    !                                                         symmetries permit.
    !
    ! Will need some serious work and adaptation by Tantalus.
    !---------------------------------------------------------------------------
    type(Moment),pointer   :: NewMoment
    integer, intent(in)    :: l,m,ImPart

    nullify(NewMoment)

    !---------------------------------------------------------------------------
    ! Selection rules, independent of axis choices.
    if((mod(l,2).ne.0)) then
      ! The multipole moments of odd order are constrained by parity.
      return
    endif

    if((m.eq.0).and.(Impart.eq.1)) then
      !Do not create a new moment for an imaginary part of moments with m=0
      return
    endif
    !---------------------------------------------------------------------------
    ! Selection rules, dependent of axis choices.
    select case(QuantisationAxis)
    case(1)
        ! Conservation of y-timesimplex
        if((ImPart.eq.1.)) then
          return
        endif
        ! Conservations of signature
        if((mod(m,2).ne.0)) then
          return
        endif
    case(2)
        if((mod(l,2) .ne. 0) .and. (mod(m,2).eq.0)) then
         return
        endif
        if((mod(l,2) .eq. 0) .and. (mod(m,2).ne.0) ) then
          return
        endif

        if((Impart.eq.0) .and. (mod(m,2).ne.0)) then
          return
        endif
        if((Impart.eq.1) .and. (mod(m,2).eq.0)) then
          return
        endif
    case(3)
        if((ImPart.eq.1.)) then
          return
        endif
        if((mod(m,2).ne.0)) then
          return
        endif
    end select 
    !---------------------------------------------------------------------------
    allocate(NewMoment) ; NewMoment%l=l ; NewMoment%m=m

    nullify(NewMoment%Prev, NewMoment%Next) 
    allocate(NewMoment%SpherHarm(nx*ny*nz))

    if(ImPart.eq.1.) then
        NewMoment%ImPart=.true.
    else
        NewMoment%ImPart=.false.
    endif

    ! The parameters of the new multipole moment are set to zero by default.
    NewMoment%ConstraintType= 0
    NewMoment%Value         = 0.0_dp
    NewMoment%SpherHarm     = 0.0_dp
    NewMoment%Squared       = 0.0_dp

    nullify(NewMoment%Calculate)
    NewMoment%Calculate   => Calculate_electric
    NewMoment%PrintMoment => PrintMoment_electric

    return
  end function NewMoment_Electric

!===============================================================================
! Calculation routines
