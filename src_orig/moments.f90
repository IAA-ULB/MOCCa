! Treatment of constraints, readjustment and contribution to sphamil. 
!===============================================================================
  
  subroutine Sphamilcontribution()
    !---------------------------------------------------------------------------
    ! This function calculates the energy contribution associated with the
    ! constraints on the multipole moments.
    !
    ! For ordinary multipole constraints
    !  h => h - \lambda * O 
    ! where lambda is the current multiplier
    !---------------------------------------------------------------------------
    integer               :: it
    type(Moment), pointer :: Current

    Current => Root
    
    Constraint_I_I = 0.0_dp
    do while(associated(Current%Next))
      Current => Current%Next

      ! Go to the next moment if this moment is not constrained
      if(Current%constrainttype.eq.0) cycle
     
      if(Current%isoswitch .eq. 0) then
        ! Apply the constraint to all species
        do it=1,2
          Constraint_I_I(:,it) = Constraint_I_I(:,it)                          &
          &                - Current%Multiplier * Current%SpherHarm*Cutoff(:,it)
        enddo
      elseif(Current%isoswitch .le. 2) then
        ! Apply the constraint to only one species
        it = Current%isoswitch
        Constraint_I_I(:,it) = Constraint_I_I(:,it)                            &
        &                  - Current%Multiplier * Current%SpherHarm*Cutoff(:,it)
      endif
    enddo
    nullify(Current)
    
  end subroutine SpHamilcontribution
  
  subroutine ReadjustAllMoments(ctype)
    !---------------------------------------------------------------------------
    ! Readjust all the multipole constraints of type ctype
    !---------------------------------------------------------------------------
    
    type(Moment), pointer :: Current
    integer, intent(in)   :: ctype

    nullify(Current)
    Current => Root

    do while(associated(Current%Next))
        Current => Current%Next
        if(Current%constrainttype .eq. ctype)  call Readjust(Current)
    enddo
    nullify(Current)
    
  end subroutine ReadjustAllMoments
  
  subroutine Readjust(ToReadjust)
    !---------------------------------------------------------------------------
    ! Subroutine that readjusts the constraint of a certain multipole moment.
    !---------------------------------------------------------------------------
    type(Moment), pointer    :: ToReadjust
    real(KIND=dp) :: slow, dl
    integer       :: it

   11 format ( '------------------------------------')
   12 format ( ' Constraint on Q_{ ', 2i2, ' has no ')
   13 format ( '                intensity parameter.')
   14 format ( ' Estimated  :', 1es12.5)
   15 format ( ' Scaling    :', 1es12.5)
   16 format ( ' Final value:', 1es12.5)

    if(ToReadjust%ConstraintType.eq.0) then
      call stp('Moment is not constrained, but still gets readjusted!')
    endif

    ! Augmented Lagrangian readjustment
    if(ToReadjust%Intensity .eq. 0.0) then
          ! Find suitable intensity, if none was found before
          
          select case(ToReadjust%isoswitch)
          case(0)
            ToReadjust%Intensity = 1d0/sum(ToReadjust%Squared) 
          case(1,2)
            it = ToReadjust%isoswitch
            ToReadjust%Intensity = 1d0/ToReadjust%Squared(it) 
          end select
          print 11
          print 12, ToReadjust%l,ToReadjust%m
          print 13
          print 14, ToReadjust%Intensity
          print 15, ToReadjust%intensityfactor
          ToReadjust%Intensity = ToReadjust%Intensity*ToReadjust%intensityfactor
          print 16, ToReadjust%Intensity
          print 11
    endif
    
    slow = ReadjustSlowdown
    if(Toreadjust%constrainttype.eq.2) slow = 2.0

    ! Set the new multiplier        
    ToReadjust%mult_hist = ToReadjust%multiplier
    
    select case(ToReadjust%isoswitch)
    case(0)
      dl = ToReadjust%Intensity*(ToReadjust%Constraint - sum(ToReadjust%Value))
    case(1,2)
      it = ToReadjust%isoswitch
      dl = ToReadjust%Intensity*(ToReadjust%Constraint -   ToReadjust%Value(it))
    end select
    ToReadjust%Multiplier =  ToReadjust%Multiplier +   slow *  dl 

    return
  end subroutine Readjust

