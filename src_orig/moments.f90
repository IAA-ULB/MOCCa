!==============================================================================
! 
! Module treating the calculation of, printing of and constraints on the 
! multipole moments of the various mean-field densities. 
!
!==============================================================================
! Hephaestos keywords
!
! MAX_ELL   : $MAX_ELL
! FILL_LIST : [much too long to reproduce]
! QUANT_AX  : $QUANT_AX
! SECOND_AX : $SECOND_AX
! TR        : $TR
! NTR       : $NTR
!==============================================================================
! 
! Spherical harmonics are taken to be in the convention of Messiah.
! They are, in terms of spherical coordinates:
!
!        Y_{l}^{m} = (-1)^{m}[(2*l+1)/4\pi (l-m)!/(l+m)!]^{1/2}
!                 *    P^{m}_{l}(cos(\theta)) e^{i m \phi}
!
! where the P^{m}_{l} are the associated Legendre Polynomials and -l <= m <= l.
! These expression on the mesh are automatically generated by recursion formula.
!
! The code "talks" about the real and imaginary parts of these moments.
! The only values for m that appear in the code are positive.
!
!   Re Y_lm =  1/2 * (Y_l+m + Y_l-m)
!   Im Y_lm = -i/2 * (Y_l+m - Y_l-m)
!
! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - 
! 
! The electric multipole moments are
!      \langle \hat{Q}^e_{lm} \rangle = \int d^3r rho(r) r^l Y_{lm} 
! The magnetic multipole moments are
!      \langle \hat{Q}^m_{lm} \rangle = Q^m_lm,spin + Q^m_lm,orbit 
!      Q^m_lm,spin                = 0.5*\int d^3r s_m(r) nabla_m(r^l Y_{lm}) 
!      Q^m_lm,orbit               =     \int d^3r (rxj)_m(r) nabla_m(r^l Y_{lm}) 
!
! Note that the magnetic moments are not calculated in this way by the code, 
! but rather by partial integration and using a vector identity for the orbit
! part.
!
! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
! The calculation of the rms charge radius and the fourth radial moment 
! also happen in this module; they are treated as multipole moments. They
! are both appended at the end of the linked list with l=-2 and -4 respectively.
! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
! For the electric multipole moments, practical quantities to investigate are
!
! Dimensionless deformation Betas
!  Beta_lm  = 4 * pi /( 3 * R_0**l * A) < Q^e_{lm} >
!           where R0 = 1.2A**(1/3)
!
! Total deformation
!  Q_l = \sqrt{ \Sum_{m = 0,..,l} f(m) [ < Re Q_{lm} >**2 + < Im Q_{lm}**2 > ]}
!         with f(m) = 2 if m \not = 0 and f(m) = 1 for m = 0.
!
! For more conversion formulae see:
!
!   W.Ryssens, V. Hellemans, M. Bender & P.-H. Heenen, CPC 187 (2015) 175-194
!   W.Ryssens, PhD Thesis (2016)
!
! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - 
!
!  For constraints, two options exist for every moment independently
!  - Augmented Lagrangian with fixed intensity
!  - Constraints with projection on feasible set
!
!  This is encoded for every multipole moment separately 
!   (0) No constraint
!   (1) Augmented Lagrangian
!   (2) Projection on feasible set
!
!  For the moment only the total value of the electric multipole moments can be
!  constrained. 
!
!-------------------------------------------------------------------------------
!
! There is a redundancy in the choice of parameterization of the multipole 
! moments: it depends on the choices made for the Cartesian reference frame. 

! There are six possibilities, corresponding to the permutations of the 
! axes of the intrinsic frame. 
!
! (x,y,z), (x,z,y), (y,x,z), (y,z,x), (z,x,y), (z,y,x)
!
! which all correspond to different parameterizations of the spherical
! coordinates in terms of (x,y,z).
!
! The distinction is made by two parameters:
!     QuantisationAxis = X/Y/Z (1,2,3)
! which determines which of the Cartesian coordinates determines the angle theta
!     x_i = r cos(theta).
! The second parameter
!     SecondaryAxis = 1/2
! simply determines the reference for the angle \phi. It determines the order of
! the two other (non-quantization) axes. 1 corresponds to lexographical order
! (x,y) while 2 corresponds to non-lexicographical order (y,x).
!
! The angle phi is determined by
!     \phi = atan2(x_2, x_1)
!
! Examples:
!    (QuantisationAxis, SecondaryAxis,Permutation)
!    (3,1, (x,y,z))
!    (3,2, (y,x,z))
!    (2,1, (x,z,y))
!    (2,2, (z,x,y))
!    (1,1, (y,z,x))
!    (1,2, (z,y,x))
!
! Note that changing from the ordinary (x,y,z) has profound consequences
! regarding which non-physical multipole moments. 
!-------------------------------------------------------------------------------
!===============================================================================
  use geninfo
  use sphericalharmonics

  implicit none
  
  !-----------------------------------------------------------------------------
  ! The technical feat of treating multipole moments on an equal footing for 
  ! any kind of (l,m) or nature of the multipole moment is accomplished by 
  ! using several linked lists of these moment type objects.
  !-----------------------------------------------------------------------------
  type Moment
      !-------------------------------------------------------------------------
      !Principal and magnetic quantum number of the multipole moment
      integer :: l,m
      !Looking at the real(.false.) or imaginary(.true.) part
      logical :: ImPart
      !-------------------------------------------------------------------------
      !The SpherHarm variable contains the values of the associated Qlm.
      !-------------------------------------------------------------------------
      real(KIND=dp), allocatable  :: SpherHarm(:)
      !-------------------------------------------------------------------------
      ! Integer controlling the type of constraint on the multipole moment.
      ! 0 - unconstrained
      ! 1 - Augmented Lagrangian
      ! 2 - Projection on feasible set
      !-------------------------------------------------------------------------
      integer       :: ConstraintType
      !-------------------------------------------------------------------------
      ! Number of iterations to employ the constraint for. Useful for putting 
      ! temporary constraint in order to initialize a calculation.
      integer       :: Iteration=-1
      !-------------------------------------------------------------------------
      ! Calculated value of the moment for neutrons and protons.
      ! (*) Scalar for mass/electric multipole moments.
      ! (*) Vector for magnetic multipole moments. 
      !      vectorvalue    : contains the integrals of the multipole moments 
      !                       over the individual densities (spin, current)
      !      physvectorvalue: contains the physical value, i.e. the sum over the
      !                       individual components in vectorvalue, weighted by
      !                       the appropriate g-factors.
      !-------------------------------------------------------------------------
      real(KIND=dp) :: Value(2)
      !                      |
      !                      > isospin index (neutrons, protons)
      real(KIND=dp) :: ChargeValue ! value of the multipole moment for the 
      !                            ! charge density
      real(KIND=dp) :: vectorvalue(3,2,2)
      !                            | | |
      !                            | | > isospin index (neutrons, protons)
      !                            | > spin/orbital index (spin, orbital)
      !                            > cartesian index (x,y,z)
      real(KIND=dp) :: physvectorvalue(3,2)
      !                                | |
      !                                | > isospin index (neutrons, protons)
      !                                > cartesian index (x,y,z)
      !-------------------------------------------------------------------------
      ! Value of the multipole at the previous iteration
      real(KIND=dp) :: history(2)
      !-------------------------------------------------------------------------
      ! Calculated value of the moment SQUARED.
      ! So < Q_{lm}^2 > and < Q_{lm}>^3
      !-------------------------------------------------------------------------
      real(KIND=dp) :: Squared(2)
      !-------------------------------------------------------------------------
      ! Value of the constraint on the multipole moment.
      real(KIND=dp) :: Constraint
      !-------------------------------------------------------------------------
      ! Value of the current value of the Lagrange multiplier
      real(KIND=dp) :: multiplier, mult_hist
      !-------------------------------------------------------------------------
      ! Deviation of the constraint with respect to the asked for value.
      real(KIND=dp) :: deviation
      !-------------------------------------------------------------------------
      ! (1)  Intensity:   Intensity of the constraint
      ! (2)  Scalefactor: Factor scaling the FeasibleProjection in evolution.f90
      ! (3)  Intensityfactor:  Factor scaling the heuristic for the intensity
      !                        of the constraint
      real(KIND=dp) :: Intensity, scalefactor, intensityfactor
      !-------------------------------------------------------------------------
      ! Pointers to the previous and next item in the linked list.
      !-------------------------------------------------------------------------
      type(Moment), pointer  :: Prev
      type(Moment), pointer  :: Next
      !-------------------------------------------------------------------------
      ! Deformation parameter Beta_lm associated with the moment.
      ! (neutrons,protons,charge,total)
      !-------------------------------------------------------------------------
      real(KIND=dp) :: Beta(4)
      !-------------------------------------------------------------------------
      ! Logical: if True, use the Lagrange multiplier as read from file.
      logical :: multfromfile = .false.
      logical :: continue     = .false.
      !-------------------------------------------------------------------------
      ! Procedure pointer to the routine used to calculate the moment.
      procedure(Calculate_electric),   pointer, nopass :: Calculate
      !-------------------------------------------------------------------------
      ! Procedure pointer to the routine used to print output of the moment.
      procedure(PrintMoment_electric), pointer, nopass :: PrintMoment
      !-------------------------------------------------------------------------
      ! Integer switch to determine whether we place the constraint on
      !
      ! 0: Total value of the multipole moment (neutrons + protons)
      ! 1: Only on the neutrons
      ! 2: Only on the protons
      !-------------------------------------------------------------------------
      integer                    :: Isoswitch = 0
  end type Moment

  !-----------------------------------------------------------------------------
  ! Maximum degree of the multipole moments that are considered in the 
  ! Tantalus calculation. Default = 10
  integer      :: MaxMoment=10, maxmoment_mag=3, maxmoment_divJ=4
  ! Maximum degree of the multipole moments that was checked by Hephaestos 
  ! for its symmetries. Hence MaxMoment <= list_size.
  integer, parameter     :: list_size = $MAX_ELL
  !-----------------------------------------------------------------------------
  ! Starting point for the linked list of moments.
  !-----------------------------------------------------------------------------
  type(Moment),save, pointer    :: Root      ! Electric multipole moments
  type(Moment), public, pointer :: Root_mag  ! Magnetic multipole moments
  type(Moment), public, pointer :: Root_divJ ! Moments of nabla cdot J
  !-----------------------------------------------------------------------------
  ! Couplings of the angular momentum to the magnetic moments
  ! Compile-time parameters to avoid any surprises.
  real(KIND=dp), parameter :: g_spin (2)= (/-3.826d0, 5.586d0/)!Spin-coupling 
  real(KIND=dp), parameter :: g_orbit(2)= (/    0.d0, 1.d0   /)!Orbital-coupling
  !-----------------------------------------------------------------------------
  ! CutoffType
  ! 0 : Density-dependent cutoff
  ! 1 : Spherical cut-off
  !-----------------------------------------------------------------------------
  integer       :: CutoffType=0
  !-----------------------------------------------------------------------------
  !Parameters of the cutoff function.
  ! 1 + exp[(\DeltaR - radd)/acut]
  ! Default values are the ones from K. Rutz et al, Nucl. Phys. A590 (1995) 690
  !-----------------------------------------------------------------------------
  real(KIND=dp) :: radd = 4._dp,acut=0.4_dp, cutfac = 10.0d0
  !-----------------------------------------------------------------------------
  !Cutoff function
  ! For 1) Neutrons, 2) Protons
  real(KIND=dp), allocatable, target :: Cutoff(:,:)
  !-----------------------------------------------------------------------------
  ! Slowdown of the readjustment of the Lagrange multipliers
  !-----------------------------------------------------------------------------
  real(KIND=dp)  :: ReadjustSlowDown=0.1_dp
  !-----------------------------------------------------------------------------
  ! Pointer to the cutoff procedure chosen.
  !-----------------------------------------------------------------------------
  abstract interface
        subroutine comp_cutoff()
        end Subroutine
  end interface
  procedure(comp_cutoff), pointer :: CompCutoff
  !-----------------------------------------------------------------------------
  ! Quadrupole moments in different representations, for printing purposes only.
  !
  ! Cartesian: QCartesian
  ! (Q,gamma): Q, G
  ! iq1, iq2 : iq1, iq2
  !-----------------------------------------------------------------------------
  real(kind=DP)   :: QCartesian(3,3,3), Q(3), G(3), iq1(3), iq2(3),  Qi(3,3)
  !-----------------------------------------------------------------------------
  ! Quantisation axis and secondary axis of the multipole moments.
  ! These are compilation-time parameters, and determined by Hephaestos.
  integer, parameter :: QuantisationAxis=$QUANT_AX, SecondaryAxis=$SECOND_AX
  !-----------------------------------------------------------------------------
  ! Contribution to the single-particle Hamiltonian by the constraints
  !  a) Electric multipole => Constraint_I_I => F_I_I
  !-----------------------------------------------------------------------------
  real(kind=dp), allocatable, target :: Constraint_I_I(:,:)
  !-----------------------------------------------------------------------------
  ! If true, the code takes ALL of the information on the constrained moments
  ! from the read-in wavefunction file.
  logical :: ContinueAll = .false.
  !-----------------------------------------------------------------------------
  ! If .true., redefine the spherical harmonics of all Qlm (l>1) at every 
  ! iteration to follow the movement of the centre-of-mass of the nucleus.
  logical :: follow_COM = .false.

contains
  
  subroutine PrintMoment_init()
    !---------------------------------------------------------------------------
    ! Print relevant information on the treatment of multipole moments at the 
    ! start of the run.
    !---------------------------------------------------------------------------
    
    character(len=1) :: Ax='Z', secAx1='X', secAx2='Y'

    1 format (31('-'), ' Multipole Moments', 31('-') )
    2 format ('Maximum l considered = ' , i3, ' (mass) ', i3, ' (magnetic) ' )

    3 format ('Quantisation Axis for the multipole moments:  ', a1)
    4 format ('  With secondary axis ordering             :  ', a1, ',', a1)
    5 format ('  Total permutation                        : ', &
    &                                        '(', a1, ',', a1, ',', a1, ')')

    6 format ('Cutoff parameters')
    7 format ('  CutoffType = ', i2)
   71 format ('  Spherical cutoff' )
   72 format ('  Density dependent cutoff')
    8 format ('  radd       = ', e9.2,/, &
    &         '  acut       = ', e9.2,/, &
    &         '  cutfac     = ', e9.2)
    
    9 format ('Correction of spherical harmonics with COM:     ACTIVE')
   91 format ('Correction of spherical harmonics with COM: NOT ACTIVE')

    print 1
    print 2, maxmoment, maxmoment_mag, maxmoment_divJ

    select case(QuantisationAxis)
    case(1)
      Ax = 'X'
      select case(SecondaryAxis)
      case(1)
        secAx1='Y'
        secAx2='Z'
      case(2)
        secAx1='Z'
        secAx2='Y'
      end select
    case(2)
      Ax = 'Y'
      select case(SecondaryAxis)
      case(1)
        secAx1='X'
        secAx2='Z'
      case(2)
        secAx1='Z'
        secAx2='X'
      end select
    case(3)
      Ax = 'Z'
      select case(SecondaryAxis)
      case(1)
        secAx1='X'
        secAx2='Y'
      case(2)
        secAx1='Y'
        secAx2='X'
      end select
    end select
    
    print 3, Ax
    print 4, SecAx1, SecAx2
    print 5, Ax, SecAx1,SecAx2
        
    if(follow_com) then
      print 9
    else
      print 91
    endif

    print 6
    print 7, cutofftype
    select case(Cutofftype)
    case(1)
      print 71
    case(2)
      print 72
    end select
    print 8, radd, acut, cutfac

    
  end subroutine PrintMoment_init
  
  subroutine IniMoments()
    !---------------------------------------------------------------------------
    ! This routine sets up all of the linked lists needed.
    ! 
    ! 1) The first moments ( l=0, m=0 ) to anchor the linked lists are created. 
    !      Root       : mass (electric) multipole moments
    !      Root_mag   : magnetic-spin multipole moments
    !      Root_divJ  : multipole moments of nabla cdot J
    ! 
    ! 2) For each of these multipole moments, we calculate the values of the 
    !    spherical harmonics on the mesh.
    !
    ! 3) The routine creates all the necessary moments using subroutine
    !    NewMoment and links them in the following order:
    !    (l,m, R/I): (0,0), (1,0), (1,1,R), (1,1,I), (2,0), (2,1,R), (2,1,I),...
    !    Moments that are automatically zero (by symmetry) are not created by
    !    NewMoment and are absent from the list.
    ! 
    ! 4) Tantalus here detects the nonphysical moments. 
    !
    ! 5) After all this, a final addition to the linked list for the 
    !    mass/electric multipole moments is made: the radius squared. 
    !    This is implemented as a multipole moment with l = -2. 
    !
    ! --------------------------------------------------------------------------

    integer :: l,m,ImPart,i,j,k
    ! Meshes containing the values of all associated Legendre Polynomials
    ! Some dimensions start at index 0, because l and m can both be 0
    real(KIND=dp),allocatable  :: SpherHarmMesh(:,:,:,:,:,:)
    type(Moment),pointer       :: NextMoment,Current
    
    real(KIND=dp), pointer     :: harm_3D(:,:,:)
    
    allocate(SpherHarmMesh(nx,ny,nz,0:MaxMoment,0:MaxMoment,2))
    !---------------------------------------------------------------------------
    ! Create the first Multipole moments: l=0, m=0
    nullify(Root) ;    allocate(Root)
    Root%l=0      ;    Root%m=0
    allocate(Root%SpherHarm(nx*ny*nz))
    
$NTR    nullify(Root_mag) ;    allocate(Root_mag)
$NTR    Root_mag%l=0      ;    Root_mag%m=0
$NTR    allocate(Root_mag%SpherHarm(nx*ny*nz))


    nullify(Root_divJ) ;    allocate(Root_divJ)
    Root_divJ%l=0      ;    Root_divJ%m=0
    allocate(Root_divJ%SpherHarm(nx*ny*nz))
    !---------------------------------------------------------------------------
    !This is the l=0,m=0 spherical harmonic
    Root%SpherHarm=1.0_dp/sqrt(4.0_dp*pi) 
    Root%Impart=.false.
    Root%ConstraintType=0
    Root%Calculate   => Calculate_electric
    Root%PrintMoment => PrintMoment_electric
    nullify(Root%Prev) ;  nullify(Root%Next)

$NTR    Root_mag%SpherHarm=1.0_dp/sqrt(4.0_dp*pi) 
$NTR    Root_mag%Impart=.false.
$NTR    Root_mag%ConstraintType=0
$NTR    ! Note that I'm not sure what the l=0,m=0 magnetic moment would be
$NTR    ! At the least it is parity violating, so just to avoid trouble, we
$NTR    ! associate these pointers with the ELECTRIC routines.
$NTR    Root_mag%Calculate   => Calculate_electric
$NTR    Root_mag%PrintMoment => PrintMoment_electric
$NTR    nullify(Root_mag%Prev) ;  nullify(Root_mag%Next)


    Root_divJ%SpherHarm=1.0_dp/sqrt(4.0_dp*pi) 
    Root_divJ%Impart=.false.
    Root_divJ%ConstraintType=0
    Root_divJ%Calculate   => Calculate_multipole_divJ
    Root_divJ%PrintMoment => PrintMoment_divJ
    nullify(Root_divJ%Prev) ;  nullify(Root_divJ%Next)
    
    !---------------------------------------------------------------------------
    ! Calculating all the spherical harmonics
    call GenSphericalHarmonics(maxmoment,nx,ny,nz,meshx,meshy,meshz,           & 
    &                          SpherHarmMesh,quantisationaxis,secondaryaxis)
    
    !---------------------------------------------------------------------------
    !Creating all the moments and assigning each moment the spherical harmonic
    ! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
    ! a) The mass/electric moments
    nullify(Current)      ;  allocate(Current)     ; Current=>Root
    nullify(Current%Next) ;  nullify(Current%Prev) ; nullify(NextMoment)
 
    do l=1,MaxMoment
      do m=0,l
        do ImPart=0,1
          NextMoment => NewMoment_electric(l,m,ImPart)
          !Placing the moment in the list
          if(associated(NextMoment)) then
            harm_3D(1:nx,1:ny,1:nz) => NextMoment%SpherHarm(:)
            harm_3D=SpherHarmMesh(:,:,:,l,m,Impart+1)
            ! Putting the pointers in the correct direction
            NextMoment%Prev => Current
            Current%Next    => NextMoment
            Current         => NextMoment
            nullify(NextMoment)
          endif
        enddo
      enddo
    enddo
   ! We append the radius squared to the ordinary list...
    NextMoment   => NewMoment_electric(-2,0,0)
    harm_3D(1:nx,1:ny,1:nz) => NextMoment%SpherHarm(:)
    NextMoment%Calculate    => Calculate_electric 

    do k=1,nz
      do j=1,ny
        do i=1,nx
          harm_3D(i,j,k) = meshx(i)**2 + meshy(j)**2 + meshz(k)**2 ! r^2
        enddo
      enddo
    enddo
    
    Current%Next    => NextMoment
    NextMoment%Prev => Current
    Current         => NextMoment
    ! .... as well as the fourth radial moment for good measure
    NextMoment   => NewMoment_electric(-4,0,0)
    harm_3D(1:nx,1:ny,1:nz) => NextMoment%SpherHarm(:)
    NextMoment%Calculate    => Calculate_electric

    do k=1,nz
      do j=1,ny
        do i=1,nx
          harm_3D(i,j,k) = (meshx(i)**2 + meshy(j)**2 + meshz(k)**2)**2 ! r^4
        enddo
      enddo
    enddo
    
    Current%Next    => NextMoment
    NextMoment%Prev => Current

    ! End of the chain
    nullify(Current)
    !---------------------------------------------------------------------------
    ! b) The magnetic moments
$NTR    allocate(Current)
$NTR    Current=>Root_mag
$NTR    nullify(Current%Next) ;  nullify(Current%Prev) ; nullify(NextMoment)
$NTR    do l=1,MaxMoment_mag
$NTR     do m=0,l
$NTR        do ImPart=0,1
$NTR          NextMoment => NewMoment_magnetic(l,m,ImPart)
$NTR          !Placing the moment in the list
$NTR          if(associated(NextMoment)) then
$NTR            harm_3D(1:nx,1:ny,1:nz) => NextMoment%SpherHarm(:)
$NTR            harm_3D=SpherHarmMesh(:,:,:,l,m,Impart+1)
$NTR
$NTR            NextMoment%Prev => Current
$NTR            Current%Next => NextMoment
$NTR            Current => NextMoment
$NTR            nullify(NextMoment)
$NTR          endif
$NTR        enddo
$NTR      enddo
$NTR    enddo
    !---------------------------------------------------------------------------
    ! c) The moments of divJ
    nullify(Current)      ;  allocate(Current)     ; Current=>Root_divJ
    nullify(Current%Next) ;  nullify(Current%Prev) ; nullify(NextMoment)
 
    do l=1,MaxMoment_divJ
      do m=0,l
        do ImPart=0,1
          ! div_J has the same symmetries as rho, so its multipole moments
          ! satisfy the same requirements
          NextMoment => NewMoment_divJ(l,m,ImPart) 
          
          !Placing the moment in the list
          if(associated(NextMoment)) then
            harm_3D(1:nx,1:ny,1:nz) => NextMoment%SpherHarm(:)
            harm_3D=SpherHarmMesh(:,:,:,l,m,Impart+1)
            ! Putting the pointers in the correct direction
            NextMoment%Prev => Current
            Current%Next    => NextMoment
            Current         => NextMoment
            nullify(NextMoment)
          endif
        enddo
      enddo
    enddo
    ! We append the radius squared to the ordinary list...
    NextMoment   => NewMoment_electric(-2,0,0)
    harm_3D(1:nx,1:ny,1:nz) => NextMoment%SpherHarm(:)
    NextMoment%Calculate    => Calculate_multipole_divJ 
    NextMoment%Printmoment  => Printmoment_divJ 

    do k=1,nz
      do j=1,ny
        do i=1,nx
          harm_3D(i,j,k) = meshx(i)**2 + meshy(j)**2 + meshz(k)**2 ! r^2
        enddo
      enddo
    enddo
    
    Current%Next    => NextMoment
    NextMoment%Prev => Current
    Current         => NextMoment
    ! .... as well as the fourth radial moment for good measure
    NextMoment   => NewMoment_electric(-4,0,0)
    harm_3D(1:nx,1:ny,1:nz) => NextMoment%SpherHarm(:)
    NextMoment%Calculate    => Calculate_multipole_divJ 
    NextMoment%Printmoment  => Printmoment_divJ 

    do k=1,nz
      do j=1,ny
        do i=1,nx
          harm_3D(i,j,k) = (meshx(i)**2 + meshy(j)**2 + meshz(k)**2)**2 ! r^4
        enddo
      enddo
    enddo
    
    Current%Next    => NextMoment
    NextMoment%Prev => Current

    ! End of the chain
    nullify(Current)
    !---------------------------------------------------------------------------
  end subroutine IniMoments

  subroutine shift_multipoles()
    !---------------------------------------------------------------------------
    ! Recenter the spherical harmonics of all multipole moments with l>1 on
    ! the centre-of-mass. 
    !---------------------------------------------------------------------------
    type(Moment), pointer      :: current
    real(KIND=dp), pointer     :: harm_3D(:,:,:)
    real(KIND=dp), allocatable :: SpherHarmMesh(:,:,:,:,:,:)
    integer                    :: im, i,j,k

    allocate(SpherHarmMesh(nx,ny,nz,0:MaxMoment,0:MaxMoment,2))

    ! Regenerate
    call GenSphericalHarmonics(maxmoment,nx,ny,nz, &
    &                          meshx_shifted,meshy_shifted,meshz_shifted,    & 
    &                          SpherHarmMesh,quantisationaxis,secondaryaxis)

    current => Root
    do while(associated(current%next)) 
      current => current%next
      
      if(current%l .ne. 1) then 
        im = 1
        if(current%impart) im = 2

        harm_3D(1:nx,1:ny,1:nz) => Current%SpherHarm(:)
        if(current%l .gt. 0) then
          harm_3D=SpherHarmMesh(:,:,:,current%l,current%m,im)
        elseif(current%l .eq. -2) then
          ! RMS radius
          do k=1,nz
            do j=1,ny
              do i=1,nx
                harm_3D(i,j,k) = meshx_shifted(i)**2 &
                &              + meshy_shifted(j)**2 &
                &              + meshz_shifted(k)**2
              enddo
            enddo
          enddo

        endif
      endif
    enddo
    deallocate(spherharmmesh)
    
  end subroutine shift_multipoles

  function NewMoment_Electric(l,m,ImPart) result(newmoment)
    !---------------------------------------------------------------------------
    ! This subroutine tries to create a new mass/electric multipole moment. 
    ! It checks a predefined list (generated by Hephaestos) whether the asked 
    ! for combination (l, m, impart) is restricted by a self-consistent symmetry
    ! or not.
    ! - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
    ! Input:
    !   l, m  : characteristic numbers of the multipole moment
    !   impart: real (0) or imaginary (1) part of multipole moment
    !
    ! Output:
    !   newmoment :  either (a) a pointer to an empty Moment extended type
    !                or    (b) an unassociated pointer
    !
    !                If the multipole moment is a relevant degree of freedom
    !                (as determined by Hephaestos from the symmetry options)
    !                then the routine returns (a), else (b).
    !---------------------------------------------------------------------------
    type(Moment),pointer   :: NewMoment
    integer, intent(in)    :: l,m,ImPart
    integer, allocatable   :: moment_list(:,:,:)

    nullify(NewMoment)

    !- - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
    ! We fill the list that decides which multipole moments are restricted by
    ! symmetry and which should be calculated. 
    !
    !  moment_list(l,m,k) = 0 => restricted by symmetry, 
    !              | | |           should not be calculated
    !              | | |
    !  moment_list(l,m,k) = 1 => should be calculated
    !              | | |
    !              | | -> k : real (0) or imaginary(1) part
    !              | ---> m : second characteristic number
    !              -----> l : first characteristic number
    !                      
    !- - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
    allocate(moment_list(0:list_size, 0:list_size, 0:1))
    moment_list = 0
    
$FILL_LIST

    ! Actually check our multipole moment
    ! ( Note that negative l are taken separately as special cases )
    if(l.ge.0) then
      if(moment_list(l,m,impart) .eq. 0) return
    endif
    deallocate(moment_list)

    !---------------------------------------------------------------------------
    ! The multipole moment is a relevant degree of freedom, create all things
    allocate(NewMoment) ; NewMoment%l=l ; NewMoment%m=m

    nullify(NewMoment%Prev, NewMoment%Next) 
    allocate(NewMoment%SpherHarm(nx*ny*nz))

    if(ImPart.eq.1.) then
        NewMoment%ImPart=.true.
    else
        NewMoment%ImPart=.false.
    endif

    ! The parameters of the new multipole moment are set to zero by default.
    NewMoment%ConstraintType  = 0
    NewMoment%Value           = 0.0_dp
    NewMoment%ChargeValue     = 0.0_dp
    NewMoment%SpherHarm       = 0.0_dp
    NewMoment%Squared         = 0.0_dp
    NewMoment%multiplier      = 0.0_dp
    NewMoment%mult_hist       = 0.0_dp
    NewMoment%scalefactor     = 1.0_dp
    NewMoment%intensity       = 0.0_dp
    NewMoment%intensityfactor = 1.0_dp
    ! Zero these for safety
    NewMoment%vectorvalue     = 0.0_dp
    NewMoment%physvectorvalue = 0.0_dp

    
    nullify(NewMoment%Calculate)
    NewMoment%Calculate   => Calculate_electric
    NewMoment%PrintMoment => PrintMoment_electric

    return
  end function NewMoment_Electric
  
