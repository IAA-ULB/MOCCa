submodule (functional) functional_coefs
!==============================================================================
!
! Implementation submodule of module functional: functional_coefs
!  Interface block lives in src_orig/functional.f90.
!
!  calcedfcoefs is the only procedure that touches the raw EDF couplings
!  (t0, x3, CSDS0, t1n2, ...) whose names are functional-dependent: the set
!  generated by Hephaestos differs per .func file, so they can never appear
!  in a stable only:-list in the parent.  Its use of the parameterization
!  module is therefore procedure-local and bare.
!
!==============================================================================
implicit none
contains

 module subroutine calcedfcoefs()
    !--------------------------------------------------------------------------
    ! Calculate the coupling constants from the expressions passed into
    ! Hephaestos.
    !--------------------------------------------------------------------------
    use parameterization

$CALCCOEF

    nucleonmass = 0.5d0*(nucleonmass(1) + nucleonmass(2))

 end subroutine calcedfcoefs

end submodule functional_coefs
