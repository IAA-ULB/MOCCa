import sys
from pyev.helpers import *


def compute_eigenvectors(na:int, nev:int, nblk:int, sequential_solution:bool):
    """
    compute and time eigenvectors

    Args:
        sequential_solution: if True computes the sequential solution using numpy.linalg.eigh and verifies the outcome.
    """
    print("\n")
    if use_pyelpa:
        from pyelpa import ProcessorLayout, DistributedMatrix, Elpa
    else:
        from pyev   import ProcessorLayout, DistributedMatrix, Elpa

    import numpy as np
    from mpi4py import MPI
    comm = MPI.COMM_WORLD

    header = f"compute_eigenvectors({na=},{nev=},{nblk=})-{comm2str(comm)}"
    if comm.Get_rank() == 0:
        # print("\n\nOutput is generated by rank 0 only, unless explicity stated, e.g. " \
        #       "'Rank[1/4] output generated by rank 1/4'")
        print(header, f"backend = {use_pyelpa}") 
    
    __symmetric__ = True
    __verbose__ = False

    def aij(i,j):
        """i and j are 0 based now - by choice, since we are fully working in Python and thus forget
        that the underlying stuff is Fortran.
        """
        if __symmetric__:
            return 1.5 if i==j else 1/np.sqrt(np.abs(i-j))
        else:
            # print(header,f"--aij({i},{j})")
            return 10*i+j

    # Set some parameters for matrix layout
    nev = na

    if sequential_solution:
        # Full matrix on all ranks for verification
        a_r = np.zeros((na,na),dtype=float)
        for j in range(na):
            for i in range(na):
                a_r[i,j] = aij(i+1,j+1)

        if MPI.COMM_WORLD.Get_rank() == 0:
            # Compute the reference solution with numpy.linalg.eigh
            eigenvalues_r, _ = np.linalg.eigh(a_r)
            if __verbose__:
                print(header, f"a_r =\n{a_r}")
                print(header, "*** np.linalg.eigh solution ***")
                for i, ev in enumerate(eigenvalues_r):
                    print(header, f"{i}: {ev}")

    # initialize processor layout, needed for calling ELPA
    comm = MPI.COMM_WORLD
    layout_p = ProcessorLayout(comm)
    
    # create arrays
    a = DistributedMatrix(layout_p, na, nev, nblk)
    eigenvectors = DistributedMatrix(layout_p, na, nev, nblk)
    eigenvalues = np.zeros(na, dtype=np.float64)
    
    # initialize elpa
    e = Elpa.from_distributed_matrix(a)
    
    # because we have a 2x2 grid of processors the following must hold:
    assert a.na_rows == a.na//2
    assert a.na_cols == a.na//2
    # set input matrix (a.data) on this core (a is stored in a block-cyclic
    # distributed layout; local size: a.na_rows x a.na_cols)
    # Caution: using this, the global matrix will not be symmetric; this is just
    # and example to show how to access the data
    for il in range(a.na_rows):
        for jl in range(a.na_cols):
            i,j = a.get_global_index(il,jl)
            a_ij = aij(i+1,j+1)
            # print(i,j,a_ij)
            a.data[il,jl] = a_ij
            # print(header, i, j, a.data[il,jl])
        if __verbose__:
            print(header, a.data[il,:])

    if sequential_solution:
        # verify that the distributede matrix and the global matrix are the same
        for il in range(a.na_rows):
            for jl in range(a.na_cols):
                i,j = a.get_global_index(il,jl)
                assert a.data[il,jl] == a_r[i,j], f"({il},{jl})->({i},{j}) : {a.data[il,jl]=} != {a_r[i,j]=}"
    
    # now compute nev of na eigenvectors and eigenvalues
    e.eigenvectors(a.data, eigenvalues, eigenvectors.data)

    # Check the result:
    if MPI.COMM_WORLD.Get_rank() == 0:
        print(header, "*** solution ***")
        if sequential_solution:
            print(header, f"{'ev[i]':>6} numpy.linalg.eigh {str(use_pyelpa):>16}")
            for i, ev in enumerate(eigenvalues_r):
                print(header, f"{i:>6}  {ev:16.9f} {eigenvalues_r[i]:16.9f}")
            norm_diff = np.linalg.norm(eigenvalues-eigenvalues_r)

            s = f"{norm_diff:8.3g}"
            print(header, f"norm_diff={s:>31}")
            assert norm_diff<1e-12, f"Parallel and sequential solutions differ more than expected: {norm_diff=}."
        else:
            print(header, f"{'ev[i]':>6} {str(use_pyelpa):>16}")
            for i, ev in enumerate(eigenvalues):
                print(header, f"{i:>6}  {eigenvalues[i]:16.9f}")

if __name__ == "__main__":
    # command line 
    #   > mpirun -n 4 python ev.py na nev nblk [-s|-e --use-pyelpa 0|1]
    # take parameters from command line arguments 1-3
    na,nev,nblk = [ int(arg) for arg in sys.argv[1:4]]
    # select backend from command line arguments
    use_pyelpa.from_argv()
    compute_eigenvectors(na, nev, nblk, 
        sequential_solution='--check' in sys.argv
    )
